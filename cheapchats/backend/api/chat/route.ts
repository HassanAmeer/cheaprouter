function saveCodeCheckpointToMemory(convId: string | null, userId: string, fullContent: string, targetModel: string) {
  if (!convId) return;
  try {
    const parsedArt = parseAllArtifactFiles(fullContent);
    let title = parsedArt?.title;
    let fileName = parsedArt?.files?.[0]?.name;
    let content = parsedArt?.content;

    if (!content && (fullContent.includes("<cheapchatArtifact") || (fullContent.match(/```/g) || []).length % 2 !== 0)) {
      const artifactMatch = fullContent.match(/<cheapchatArtifact\s+[^>]*title="([^"]+)"/i);
      const actionMatch = fullContent.match(/<cheapchatAction\s+[^>]*filePath="([^"]+)"/i);
      const codeBlockMatch = fullContent.match(/```[a-zA-Z0-9_-]*\n?([\s\S]+)$/i);

      title = artifactMatch?.[1] || title || "Project";
      fileName = actionMatch?.[1] || fileName || "index.html";
      content = actionMatch?.[3] || codeBlockMatch?.[1] || "";
    }

    if (content) {
      const c = content.trim();
      const isHtml = c.includes("<html") || c.includes("<!DOCTYPE");
      const isComplete = isHtml
        ? (c.includes("</html>") && c.includes("</script>"))
        : (c.endsWith("}") || c.endsWith(");") || c.endsWith("```"));
      const hasUnclosed = (fullContent.match(/```/g) || []).length % 2 !== 0 ||
        (fullContent.includes("<cheapchatArtifact") && !fullContent.includes("</cheapchatArtifact>"));
      const isPartial = !isComplete || hasUnclosed;

      const memKey = `code_checkpoint_${convId}`;
      const existingMem = db.select().from(memories).where(eq(memories.key, memKey)).get();
      const memPayload = JSON.stringify({
        title,
        fileName: fileName || "index.html",
        isPartial,
        fullCode: c,
        lineCount: c.split("\n").length,
        model: targetModel,
        updatedAt: Date.now(),
      });

      const summaryText = `Code Checkpoint [${title}]: ${isPartial ? "PARTIAL / INCOMPLETE" : "COMPLETE"} (${c.split("\n").length} lines). Generated by: ${targetModel}`;

      if (existingMem) {
        db.update(memories)
          .set({
            value: summaryText,
            content: memPayload,
            isUsed: 1,
          })
          .where(eq(memories.id, existingMem.id))
          .run();
      } else {
        db.insert(memories)
          .values({
            id: `mem_ckpt_${Date.now()}`,
            userId,
            key: memKey,
            value: summaryText,
            content: memPayload,
            isUsed: 1,
            createdAt: Date.now(),
          })
          .run();
      }
    }
  } catch (err) {
    console.warn("Failed to save code checkpoint to memory:", err);
  }
}

function parseSSEChunk(
  chunkText: string,
  onComplete: (payload: string) => void
): { text: string; leftover: string } {
  let carryOver = "";
  let fullText = "";
  const events = `${carryOver}${chunkText}`.split("\n\n");
  carryOver = events.pop() || "";
  for (const event of events) {
    const payload = event
      .split("\n")
      .filter((line) => line.startsWith("data:"))
      .map((line) => line.slice(5).trim())
      .join("\n");
    if (payload && payload !== "[DONE]") onComplete(payload);
  }
  return { text: fullText, leftover: carryOver };
}

